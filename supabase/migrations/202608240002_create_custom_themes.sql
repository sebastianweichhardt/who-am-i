create table if not exists public.custom_themes (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null check (char_length(btrim(title)) between 1 and 80),
  description text not null default '' check (char_length(description) <= 160),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.custom_theme_entries (
  id bigint generated by default as identity primary key,
  theme_id uuid not null references public.custom_themes(id) on delete cascade,
  prompt text not null check (char_length(btrim(prompt)) between 1 and 120),
  sort_order integer not null check (sort_order >= 0),
  created_at timestamptz not null default now(),
  unique (theme_id, sort_order)
);

create index if not exists custom_themes_user_created_idx
  on public.custom_themes (user_id, created_at desc);

create index if not exists custom_theme_entries_theme_idx
  on public.custom_theme_entries (theme_id, sort_order);

create unique index if not exists custom_theme_entries_unique_prompt_idx
  on public.custom_theme_entries (theme_id, lower(btrim(prompt)));

alter table public.custom_themes enable row level security;
alter table public.custom_theme_entries enable row level security;

revoke all on table public.custom_themes from anon, authenticated;
revoke all on table public.custom_theme_entries from anon, authenticated;
grant select, insert, update, delete on table public.custom_themes to authenticated;
grant select, insert, update, delete on table public.custom_theme_entries to authenticated;
grant usage, select on sequence public.custom_theme_entries_id_seq to authenticated;


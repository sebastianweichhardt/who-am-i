create or replace function public.create_custom_theme(
  p_title text,
  p_description text,
  p_entries text[]
)
returns uuid
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
  v_theme_id uuid;
  v_title text := btrim(coalesce(p_title, ''));
  v_description text := btrim(coalesce(p_description, ''));
  v_entry_count integer;
begin
  if v_user_id is null then
    raise exception 'Authentication is required.' using errcode = '42501';
  end if;

  if char_length(v_title) not between 1 and 80 then
    raise exception 'Theme title must be between 1 and 80 characters.';
  end if;

  if char_length(v_description) > 160 then
    raise exception 'Theme description cannot exceed 160 characters.';
  end if;

  select count(*)
  into v_entry_count
  from unnest(coalesce(p_entries, array[]::text[])) as entry(prompt)
  where btrim(prompt) <> '';

  if v_entry_count < 1 then
    raise exception 'Add at least one entry.';
  end if;

  if v_entry_count > 100 then
    raise exception 'A custom theme can contain at most 100 entries.';
  end if;

  if exists (
    select 1
    from unnest(coalesce(p_entries, array[]::text[])) as entry(prompt)
    where btrim(prompt) <> ''
    group by lower(btrim(prompt))
    having count(*) > 1
  ) then
    raise exception 'Each entry must be unique.';
  end if;

  if exists (
    select 1
    from unnest(coalesce(p_entries, array[]::text[])) as entry(prompt)
    where btrim(prompt) <> ''
      and char_length(btrim(prompt)) > 120
  ) then
    raise exception 'Entries cannot exceed 120 characters.';
  end if;

  insert into public.custom_themes (user_id, title, description)
  values (v_user_id, v_title, v_description)
  returning id into v_theme_id;

  insert into public.custom_theme_entries (theme_id, prompt, sort_order)
  select v_theme_id, btrim(entry.prompt), (entry.ordinality - 1)::integer
  from unnest(p_entries) with ordinality as entry(prompt, ordinality)
  where btrim(entry.prompt) <> ''
  order by entry.ordinality;

  return v_theme_id;
end;
$$;

revoke all on function public.create_custom_theme(text, text, text[]) from public, anon;
grant execute on function public.create_custom_theme(text, text, text[]) to authenticated;
